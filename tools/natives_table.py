"""The table of rewrites for the runtime: every `native` line of tools/hints.txt.

    python tools/natives_table.py pc/gen/natives.c

Each entry says at which ROM address (bank, address) a Native of pc/native/
takes over from the original code.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    entries = []
    for line in open(os.path.join(HERE, 'hints.txt')):
        p = line.split()
        if len(p) >= 3 and p[0] == 'native':
            bank, addr = p[1].split(':')
            entries.append((int(bank, 16), int(addr, 16), p[2]))
    out = ['// Generated by tools/natives_table.py from tools/hints.txt. Do not edit.',
           '#include "../runtime/native.h"', '']
    out += ['extern Native %s;' % n for n in sorted(set(e[2] for e in entries))]
    out += ['', 'const NativeEntry native_table[] = {']
    out += ['\t{ 0x%02X, 0x%04X, &%s },' % e for e in sorted(entries)]
    out += ['};', 'const int native_table_size = %d;' % len(entries), '']
    text = '\n'.join(out)
    old = open(sys.argv[1], newline='').read() if os.path.exists(sys.argv[1]) else None
    if old != text:
        os.makedirs(os.path.dirname(os.path.abspath(sys.argv[1])), exist_ok=True)
        with open(sys.argv[1], 'w', newline='\n') as f:
            f.write(text)
    print('%d rewrites' % len(entries))


if __name__ == '__main__':
    main()

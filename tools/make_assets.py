"""Build the asset pack the PC version runs from.

    python make_assets.py <rom> <out.pak>

The ROM is only read here. The pack holds the game's data in named entries;
the exe rebuilds, at start-up, the bytes the original code still reads in
ROM layout from those entries (pc/runtime/assets.c), so it never opens the
ROM itself.

Each 16 KB bank is described by a list of regions. A region is either
  raw        the bytes, stored as an entry (still to be decoded), or
  <decoder>  a structured entry plus the rule that rebuilds the bytes.
Every decoder is checked here: if rebuilding its region does not give back
exactly the ROM's bytes, the region is stored raw instead and reported, so
the pack is always faithful. The goal is to have no raw regions left.

Pack format (little-endian): "U4PK", u32 count, then per entry: u16 name
length, name (UTF-8), u32 data length, data.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pack_formats  # noqa: E402

BANK = 0x4000
CODE_BANKS = (0, 1, 2, 3, 31)   # program banks (31: sound driver and music)


def write_pack(path, entries):
    with open(path, 'wb') as f:
        f.write(b'U4PK' + struct.pack('<I', len(entries)))
        for name, data in entries:
            n = name.encode('utf-8')
            f.write(struct.pack('<H', len(n)) + n + struct.pack('<I', len(data)) + data)


def layout_params(kind, data):
    """What the exe's importer (pc/runtime/import.c) needs besides the ROM to
    cut a region into its entry: counts and chunk boundaries, never data."""
    if kind == 'string_table':
        return [struct.unpack_from('<H', data)[0]]
    if kind == 'dungeon_bank':
        return [data[0], data[1]]
    if kind == 'chunks':
        n = struct.unpack_from('<H', data)[0]
        out, p = [n], 2
        for _ in range(n):
            t, tag = data[p], data[p + 1]
            ln = struct.unpack_from('<H', data, p + 2)[0]
            if t == 0:
                out += [0, tag, ln]
                p += 4 + ln
            else:
                k = struct.unpack_from('<H', data, p + 4 + ln)[0]
                out += [1, tag, 0]
                p += 6 + ln + k
        return out
    return []


def write_layout_header(path, layout, entries):
    """pc/gen/pack_layout.c: the region list as C data, so the exe can build
    the pack from a ROM itself. Offsets, kinds and counts only."""
    lines = ['// Generated by tools/make_assets.py --layout-header. Regions of the asset pack.',
             '#include "../runtime/import.h"', '']
    params, rows = [], []
    for b, s, n, k, e in layout:
        prm = layout_params(k, entries[e]) if k != 'raw' else []
        rows.append('	{ %d, 0x%04X, 0x%04X, "%s", "%s", %d, %d },' % (b, s, n, k, e, len(params), len(prm)))
        params += prm
    lines.append('const uint16_t pack_params[] = { %s };' % (', '.join(str(x) for x in params) or '0'))
    lines.append('const PackRegion pack_regions[] = {')
    lines += rows
    lines.append('};')
    lines.append('const int pack_region_count = %d;' % len(rows))
    with open(path, 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')


def main():
    rom = open(sys.argv[1], 'rb').read()
    entries = []
    layout = []      # (bank, start, length, kind, entry name)
    raw_bytes = 0
    for bank in range(len(rom) // BANK):
        regions = pack_formats.regions_for_bank(rom, bank)
        pos = 0
        for start, length, kind, encode in sorted(regions) + [(BANK, 0, None, None)]:
            if start > pos:   # gap: keep as raw
                name = 'raw/bank%02d_%04X' % (bank, pos)
                entries.append((name, rom[bank * BANK + pos: bank * BANK + start]))
                layout.append((bank, pos, start - pos, 'raw', name))
                raw_bytes += start - pos
            if kind is None:
                break
            original = rom[bank * BANK + start: bank * BANK + start + length]
            name, data = encode()
            rebuilt = pack_formats.rebuild(kind, data, length, start, bank)
            if rebuilt != original:
                print('bank %d $%04X: %s does not rebuild exactly; stored raw' % (bank, start, kind))
                name = 'raw/bank%02d_%04X' % (bank, start)
                entries.append((name, original))
                layout.append((bank, start, length, 'raw', name))
                raw_bytes += length
            else:
                if not any(e[0] == name for e in entries):   # one entry can serve several regions
                    entries.append((name, data))
                layout.append((bank, start, length, kind, name))
            pos = start + length
    lay = b''.join(struct.pack('<BHH', b, s, n) + struct.pack('<H', len(k)) + k.encode() +
                   struct.pack('<H', len(e)) + e.encode() for b, s, n, k, e in layout)
    entries.insert(0, ('layout', struct.pack('<I', len(layout)) + lay))
    write_pack(sys.argv[2], entries)
    if '--layout-header' in sys.argv:
        write_layout_header(sys.argv[sys.argv.index('--layout-header') + 1], layout, dict(entries))
    code_raw = sum(n for b, s_, n, k, e in layout if k == 'raw' and b in CODE_BANKS)
    print('%d entries; %d of %d bytes still raw (%.0f%%): %d in the code banks, %d data' % (
        len(entries), raw_bytes, len(rom), 100.0 * raw_bytes / len(rom), code_raw, raw_bytes - code_raw))
    for b, s_, n, k, e in layout:
        if k == 'raw' and b not in CODE_BANKS and n >= 256:
            print('  raw data: bank %2d $%04X-$%04X (%d bytes)' % (b, 0x8000 + s_, 0x8000 + s_ + n - 1, n))


if __name__ == '__main__':
    main()

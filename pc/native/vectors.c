// Bank 1's far-call vectors ($7E00-$7F77): 126 "jp routine" that the
// other banks call (bank 3 especially), and the sound driver's 8 at
// $8000 of bank 31. Each is its jp: 10 cycles, then on to the routine
// (read from the vector, so the table stays the ROM's).
#include "../runtime/native.h"
#include "../runtime/sms.h"
#include "../runtime/z80.h"
#include "game.h"

static void jump(uint16_t at) {
	cpu.cycles += 10;
	native_boundary();
	native_continue_at((uint16_t)(mem_read((uint16_t)(at + 1)) | mem_read((uint16_t)(at + 2)) << 8));
}

#define VEC(a) static void vec_##a(void) { jump(0x##a); } \
	Native native_vec_##a = { "vec_" #a, 0x##a, 1, vec_##a, 0, .long_calls = 1 };

